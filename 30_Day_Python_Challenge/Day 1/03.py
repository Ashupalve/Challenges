# Write a program to find the area and perimeter of a rectangle given its length and width

length = float (input ("Enter the length of the rectangle :"))
width = float (input ("Enter the width of the rectangle :"))

area =  length * width
perimeter = 2*(length + width )

print (f"Area of given rectangle is : {area} \nPerimeter of given rectangle is : {perimeter}")
print ("Thank you for using this programm")